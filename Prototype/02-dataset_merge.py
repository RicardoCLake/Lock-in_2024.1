import os
import glob
import pandas as pd

def merge_wifi_data(input_folder="data", output_folder="data_merged", device_id="R1"):
    """
    Reads all CSV files from the input folder, merges them, and pivots the data
    so that each row is a unique timestamp and columns are AP MAC addresses.
    """
    # 1. Locate all CSV files in the target directory
    file_pattern = os.path.join(input_folder, "*.csv")
    csv_files = glob.glob(file_pattern)
    
    if not csv_files:
        print(f"No CSV files found in the '{input_folder}' directory.")
        return

    # 2. Read and concatenate all datasets efficiently
    dataframes = [pd.read_csv(file, index_col=0) if 'Unnamed: 0' in pd.read_csv(file, nrows=0).columns else pd.read_csv(file) for file in csv_files]
    df_all = pd.concat(dataframes, ignore_index=True)

    # 3. Add the required device_id column
    df_all['device_id'] = device_id

    # 4. Pivot the dataframe
    # Using pivot_table with aggfunc='max' safely handles any rare duplicate MAC reads at the exact same timestamp
    df_pivoted = df_all.pivot_table(
        index=['timestamp', 'room', 'device_id', 'door_status', 'room_part'],
        columns='ap_mac',
        values='rssi',
        aggfunc='max'
    ).reset_index()

    # Rename the axes to remove the 'ap_mac' label generated by the pivot_table
    df_pivoted.columns.name = None

    # 5. Create the output directory if it doesn't exist
    os.makedirs(output_folder, exist_ok=True)

    # 6. Save the formatted dataset
    output_path = os.path.join(output_folder, f"{device_id}-data_merged.csv")
    
    # index=True generates the leading comma and numbered index column as requested in your example
    df_pivoted.to_csv(output_path, index=True)
    
    print(f"Successfully processed {len(csv_files)} files.")
    print(f"Merged dataset saved to: {output_path}")
    print(f"Total samples (rows): {len(df_pivoted)}")
    print(f"Total unique APs (MAC columns): {len(df_pivoted.columns) - 5}")

if __name__ == "__main__":
    device = ""
    while device == "":
        device = input("Give-me the device name:")
    input_path = ""
    while input_path == "":
        input_path = input("Give-me the input folder path:")
    merge_wifi_data(device_id=device, input_folder=input_path)